let lang = 'es';
const listeners = new Set();

/** The console's language (CFGU_GetSystemLanguage on 3DS; the browser's here). */
export function detectLang() {
  for (const tag of navigator.languages || [navigator.language || 'en']) {
    const code = tag.slice(0, 2).toLowerCase();
    if (LANGUAGES.some((l) => l.id === code)) return code;
  }
  return 'en';
}

export function setLang(next) {
  lang = STRINGS[next] ? next : 'en';
  document.documentElement.lang = lang;
  listeners.forEach((fn) => fn(lang));
}
export const getLang = () => lang;
export const onLang = (fn) => (listeners.add(fn), () => listeners.delete(fn));

export function t(key, vars) {
  let s = STRINGS[lang][key] ?? (lang === 'es' ? null : STRINGS.en[key]) ?? STRINGS.es[key];
  if (s == null) {
    console.warn('[i18n] missing', key);
    return key;
  }
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
  return s;
}

/** Localizes catalog values: "text" | { es, en } | arrays of those. */
export function L(value) {
  if (value == null) return '';
  if (Array.isArray(value)) return value.map(L);
  if (typeof value === 'object') return value[lang] ?? (lang === 'es' ? value.en : value.en ?? value.es) ?? value.es ?? '';
  return value;
}

export function fmtSize(bytes) {
  const units = ['B', 'KB', 'MB', 'GB'];
  let v = bytes;
  let u = 0;
  while (v >= 1024 && u < units.length - 1) {
    v /= 1024;
    u++;
  }
  const digits = v >= 100 || u === 0 ? 0 : 1;
  return `${v.toLocaleString(lang, { maximumFractionDigits: digits, minimumFractionDigits: digits })} ${units[u]}`;
}

export function fmtDate(iso) {
  return new Date(iso + 'T12:00:00').toLocaleDateString(lang, { day: 'numeric', month: 'short', year: 'numeric' });
}

export function fmtEta(seconds) {
  if (!isFinite(seconds)) return '…';
  if (seconds < 60) return t('eta.s', { n: Math.max(1, Math.round(seconds)) });
  return t('eta.m', { n: Math.round(seconds / 60) });
}

export function fmtStars(n) {
  return n >= 1000 ? `${(n / 1000).toLocaleString(lang, { maximumFractionDigits: 1 })}k` : String(n);
}
