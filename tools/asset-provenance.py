#!/usr/bin/env python3
"""Inventory distributable media using only recorded source context, never inferred rights."""
from pathlib import Path
import hashlib,json
ROOT=Path(__file__).resolve().parents[1]
apps={a['id']:a for a in json.loads((ROOT/'catalog/forge-store.json').read_text())['apps']}
items=[]
for p in sorted((ROOT/'assets').rglob('*')):
    if not p.is_file() or p.name=='provenance.json':continue
    rel=p.relative_to(ROOT).as_posix(); parts=p.relative_to(ROOT/'assets').parts
    source='Existing Forge project asset; source-specific permission not established in this repository.'
    license='No blanket reuse license; see LICENSE.md.'
    if parts[0]=='ports' and parts[1] in apps:
        a=apps[parts[1]];source='https://github.com/'+a.get('repo','EstebanPdN')
    elif parts[0]=='store-resources':source='tools/pack-video.py; browser originals in assets/ports; reviewed report.json'
    elif parts[0]=='fonts':source='Bundled typefaces; see adjacent OFL texts and docs/legal/THIRD_PARTY_NOTICES.md';license='SIL OFL where supplied; verify the matching font notice.'
    elif parts[0] in ('brand','audio'):source='Esteban’s Forge portfolio; imported by tools/prepare-assets.sh'
    items.append({'path':rel,'bytes':p.stat().st_size,'sha256':hashlib.sha256(p.read_bytes()).hexdigest(),'source_context':source,'rights':license})
(ROOT/'assets/provenance.json').write_text(json.dumps({'files':items},indent=2)+'\n')
lines=['# Asset credits and source register','','Generated by `python3 tools/asset-provenance.py`. '+str(len(items))+' files.','',
'This register records available context and hashes, not a grant of reuse rights. Game imagery belongs to its original owners. Source context is not a claim that an asset was authored by the repository owner. See [Rights and licenses](../LICENSE.md) and [Third-party notices](legal/THIRD_PARTY_NOTICES.md).','',
'Native RomFS contains generated versions of these visual/audio inputs plus a Universal-DB art snapshot. It is retained to make a normal native build reproducible without private source projects. System-font fallback glyphs have the limitations recorded in the third-party notices.','',
'| File | Source context | SHA-256 |','| --- | --- | --- |']
for x in items:lines.append(f"| `{x['path']}` | {x['source_context']} | `{x['sha256']}` |")
(ROOT/'docs/ASSET-CREDITS.md').write_text('\n'.join(lines)+'\n')
print('Asset register:',len(items),'files')
